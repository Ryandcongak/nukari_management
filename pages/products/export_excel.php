function makeSheet($spreadsheet, $title, $period, $headers, $rows, $moneyCols=[], $decimalCols=[]) {
    $sheet = $spreadsheet->createSheet();
    $sheet->setTitle(substr($title,0,31));
    setupSheet($sheet, $title);
    addTitle($sheet, $title, $period);
    $sheet->fromArray($headers, null, 'A4');
    $lastCol = chr(ord('A') + count($headers) - 1);
    headerStyle($sheet, 'A4:'.$lastCol.'4');
    $r=5;
    foreach($rows as $row){$sheet->fromArray($row, null, "A$r");$r++;}
    if($r>5){tableStyle($sheet, 'A4:'.$lastCol.($r-1));}
    foreach($moneyCols as $col){ if($r>5) setMoney($sheet, $col.'5:'.$col.($r-1)); }
    foreach($decimalCols as $col){ if($r>5) setDecimal($sheet, $col.'5:'.$col.($r-1)); }
    for($i=1;$i<=count($headers);$i++){
        $sheet->getColumnDimensionByColumn($i)->setAutoSize(true);
    }
    return $sheet;
}

