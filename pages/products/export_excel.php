function report_date($value) {
    $value = trim((string)$value);
    if ($value === '') return '';
    $dt = DateTime::createFromFormat('Y-m-d', $value);
    return $dt ? $dt->format('Y-m-d') : '';
}
function period_sql($column, $from, $to, &$params) {
    $where = [];
    if ($from !== '') { $where[] = "$column >= ?"; $params[] = $from; }
    if ($to !== '') { $where[] = "$column <= ?"; $params[] = $to; }
    return $where ? (' WHERE ' . implode(' AND ', $where)) : '';
}
function fetch_one($pdo, $sql, $params = []) {
    $st = $pdo->prepare($sql);
    $st->execute($params);
    return $st->fetch(PDO::FETCH_ASSOC) ?: [];
}
function fetch_all($pdo, $sql, $params = []) {
    $st = $pdo->prepare($sql);
    $st->execute($params);
    return $st->fetchAll(PDO::FETCH_ASSOC);
}
function money_num($v) { return (float)($v ?? 0); }
function setMoney($sheet, $range) {
    $sheet->getStyle($range)->getNumberFormat()->setFormatCode('"Rp" #,##0');
}
function setDecimal($sheet, $range) {
    $sheet->getStyle($range)->getNumberFormat()->setFormatCode('#,##0.###');
}
function setupSheet($sheet, $title = '') {
    $sheet->getPageSetup()
        ->setOrientation(PageSetup::ORIENTATION_LANDSCAPE)
        ->setPaperSize(PageSetup::PAPERSIZE_A4)
        ->setFitToWidth(1)
        ->setFitToHeight(0);
    $sheet->getPageMargins()->setTop(0.35)->setRight(0.25)->setLeft(0.25)->setBottom(0.35);
    $sheet->getHeaderFooter()->setOddHeader('&L&BPT Nukari Kriya Raya&R&B' . $title);
    $sheet->getHeaderFooter()->setOddFooter('&LGenerated by Nukari Management&RPage &P of &N');
    $sheet->freezePane('A6');
}
function titleStyle($sheet, $range) {
    $sheet->getStyle($range)->getFont()->setBold(true)->setSize(16)->getColor()->setRGB('07553F');
}
function subtitleStyle($sheet, $range) {
    $sheet->getStyle($range)->getFont()->setSize(10)->getColor()->setRGB('667085');
}
function headerStyle($sheet, $range) {
    $sheet->getStyle($range)->getFont()->setBold(true)->getColor()->setRGB('FFFFFF');
    $sheet->getStyle($range)->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB('07553F');
    $sheet->getStyle($range)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER)->setVertical(Alignment::VERTICAL_CENTER);
    $sheet->getStyle($range)->getBorders()->getAllBorders()->setBorderStyle(Border::BORDER_THIN)->getColor()->setRGB('D9E2EC');
}
function tableStyle($sheet, $range) {
    $sheet->getStyle($range)->getBorders()->getAllBorders()->setBorderStyle(Border::BORDER_THIN)->getColor()->setRGB('D9E2EC');
    $sheet->getStyle($range)->getAlignment()->setVertical(Alignment::VERTICAL_CENTER);
}
function kpiBox($sheet, $cell, $label, $value) {
    [$col, $row] = coordinateFromStringCustom($cell);
    $endCol = chr(ord($col)+1);
    $sheet->mergeCells($cell.':'.$endCol.($row+1));
    $sheet->setCellValue($cell, $label . "\n" . $value);
    $sheet->getStyle($cell)->getFont()->setBold(true)->setSize(11);
    $sheet->getStyle($cell)->getAlignment()->setWrapText(true)->setVertical(Alignment::VERTICAL_CENTER);
    $sheet->getStyle($cell.':'.$endCol.($row+1))->getFill()->setFillType(Fill::FILL_SOLID)->getStartColor()->setRGB('E8F5EE');
    $sheet->getStyle($cell.':'.$endCol.($row+1))->getBorders()->getAllBorders()->setBorderStyle(Border::BORDER_THIN)->getColor()->setRGB('CFE8DA');
}
function coordinateFromStringCustom($cell) {
    preg_match('/^([A-Z]+)(\d+)$/', $cell, $m);
    return [$m[1], (int)$m[2]];
}
function addTitle($sheet, $title, $period) {
    $sheet->mergeCells('A1:H1');
    $sheet->setCellValue('A1', $title);
    titleStyle($sheet, 'A1');
    $sheet->mergeCells('A2:H2');
    $sheet->setCellValue('A2', 'PT Nukari Kriya Raya | Periode: ' . $period . ' | Dicetak: ' . date('d/m/Y H:i'));
    subtitleStyle($sheet, 'A2');
}

